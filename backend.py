FLIGHT_AGENT_PROMPT = """
You are a travel flight expert.

User Query:
{query}

Airport Information:
{airport_data}

Airline Information:
{airline_data}

Generate:

1. Likely departure airport
2. Likely arrival airport
3. Airlines serving this route
4. Typical flight duration
5. Estimated airfare range
6. Peak season pricing warning
7. Booking advice

Return concise travel guidance.
"""

def flight_agent(state: TravelState):
    print("\nINSIDE FLIGHT AGENT\n")

    query = state["user_query"]

    def _api_error(result) -> bool:
        """Return True if the MCP tool returned an API error response (not an exception)."""
        return isinstance(result, list) and any(
            "error" in str(item) or "function_access_restricted" in str(item)
            for item in result
        )

    try:
        airports = asyncio.run(aviationstack_mcp_search("list_airports"))
        airlines = asyncio.run(aviationstack_mcp_search("list_airlines"))

        print("\nAIRPORTS:", airports)
        print("\nAIRLINES:", airlines)

        prompt = FLIGHT_AGENT_PROMPT.format(
            query=query,
            airport_data=str(airports)[:3000],
            airline_data=str(airlines)[:3000]
        )

        response = llm.invoke([
            SystemMessage(content="You are an expert travel flight planner."),
            HumanMessage(content=prompt)
        ])

        flight_data = response.content

    except Exception as e:
        flight_data = f"Flight information unavailable: {str(e)}"

    return {
        "flight_results": flight_data,
        "messages": [AIMessage(content="Flight recommendations generated")],
        "llm_calls": state.get("llm_calls", 0) + 1
    }


# =========================
# Hotel Agent
# =========================
# Uses Tavily (an AI-powered web search API) to find hotel recommendations.
# Does NOT use the LLM — Tavily does the searching.
# Writes results into state["hotel_results"].

def hotel_agent(state: TravelState):
    query = f"Best hotels for {state['user_query']}"
    # tavily_mcp_search is an async function (it uses the MCP async client).
    # asyncio.run() bridges the sync agent into the async call and blocks until
    # the search result is returned before the agent continues.
    hotel_results = asyncio.run(tavily_mcp_search(query))

    return {
        "hotel_results": hotel_results,
        "messages": [
            AIMessage(content="Hotel information fetched.")
        ],
        "llm_calls": state.get("llm_calls", 0) + 1
    }

def weather_agent(state: TravelState):
    city = extract_destination(state["user_query"])

    weather_data = asyncio.run(
        weather_mcp_search(city)
    )

    forecast_data = asyncio.run(
        forecast_mcp_search(city)
    )

    return {
        "weather_results": f"""
        Current Weather:
        {weather_data}

        Forecast:
        {forecast_data}
        """,
        "messages": [
            AIMessage(
                content="Weather information fetched"
            )
        ],
        "llm_calls": state.get("llm_calls", 0) + 1
    }

# =========================
# Itinerary Agent
# =========================
# First agent that calls the LLM. It receives the raw flight and hotel data
# and asks the model to synthesize a practical day-by-day itinerary.
# Writes the plan into state["itinerary"].

def itinerary_agent(state: TravelState):
    # Tavily hotel results can be thousands of tokens of raw article text.
    # Truncate before passing to the LLM to avoid hitting token limits.
    hotel_summary = str(state['hotel_results'])[:2500]

    prompt = f"""
Create a complete travel itinerary.

User Query:
{state['user_query']}

Flight Results:
{state['flight_results']}

Hotel Results:
{hotel_summary}

Weather Results:
{state['weather_results']}


Make the itinerary practical, budget-aware, and easy to follow.
"""

    response = llm.invoke([
        SystemMessage(content="You are an expert travel planner."),
        HumanMessage(content=prompt)
    ])

    return {
        "itinerary": response.content,
        "messages": [response],
        "llm_calls": state.get("llm_calls", 0) + 1
    }

# =========================
# Final Response Agent
# =========================
# Takes everything accumulated in state and asks the LLM to produce a
# single, beautifully formatted response that the user will actually see.
# This is the last node before END, so its message becomes the final answer.

def final_agent(state: TravelState):
    # final_agent only needs the synthesized itinerary — itinerary_agent already
    # combined flights, hotels, and weather into it. Re-passing the raw fields
    # here was the cause of the 8000-token Groq limit being exceeded.
    final_prompt = f"""
Generate the final travel response for the user.

User Request:
{state['user_query']}

Weather:
{str(state['weather_results'])[:600]}

Itinerary (includes flights, hotels, and day-by-day plan):
{state['itinerary']}

Format the final answer beautifully using these sections:

1. Trip Summary
2. Flight Information
3. Hotel Suggestions
4. Weather Information
5. Day-by-Day Itinerary
6. Estimated Budget
7. Final Recommendations

Important:
- Be clear and practical.
- Mention that live flight API may not provide ticket prices if pricing is unavailable.
- Keep the response useful for real travel planning.
"""

    response = llm.invoke([
        SystemMessage(content="You are a professional AI travel booking assistant."),
        HumanMessage(content=final_prompt)
    ])

    return {
        "messages": [response],
        "llm_calls": state.get("llm_calls", 0) + 1
    }

# =========================
# Build Graph
# =========================
# This section wires the four agents into a linear pipeline.
#
# Execution order:
#   START → flight_agent → hotel_agent → itinerary_agent → final_agent → END
#
# Each add_node() registers an agent function.
# Each add_edge() defines the execution order between nodes.

graph = StateGraph(TravelState)

graph.add_node("flight_agent", flight_agent)
graph.add_node("hotel_agent", hotel_agent)
graph.add_node("weather_agent", weather_agent)
graph.add_node("itinerary_agent", itinerary_agent)
graph.add_node("final_agent", final_agent)

graph.add_edge(START, "flight_agent")
graph.add_edge("flight_agent", "hotel_agent")
graph.add_edge("hotel_agent", "weather_agent")
graph.add_edge("weather_agent", "itinerary_agent")
graph.add_edge("itinerary_agent", "final_agent")
graph.add_edge("final_agent", END)

# =========================
# PostgreSQL Checkpointer
# =========================
# The checkpointer saves the full TravelState to Postgres after every node.
# This enables:
#   - Conversation memory across multiple messages (via thread_id)
#   - State recovery if the server restarts mid-run
#
# checkpointer.setup() creates the required tables in Postgres on first run.
# It is safe to call on every startup — it's idempotent.

DATABASE_URL = get_database_url()

_conn = psycopg.connect(
    DATABASE_URL,
    autocommit=True,
    row_factory=dict_row
)

checkpointer = PostgresSaver(_conn)
checkpointer.setup()

# Compile the graph with the checkpointer attached.
# After this point, travel_graph is the callable AI pipeline.
travel_graph = graph.compile(checkpointer=checkpointer)

# =========================
# Function for FastAPI
# =========================

def run_travel_agent(user_input: str, thread_id: str | None = None):
    """
    Entry point called by the FastAPI routes in app.py.

    Args:
        user_input: The user's travel query, e.g. "Plan a 5-day trip to Tokyo"
        thread_id:  Optional conversation ID. If None, a new unique ID is created.
                    Pass the same thread_id on follow-up messages to continue a
                    conversation — LangGraph will load the previous state from Postgres.

    Returns:
        A dict with:
            thread_id      — use this in subsequent requests to continue the conversation
            answer         — the final formatted travel plan (from final_agent)
            flight_results — raw flight data
            hotel_results  — raw hotel search results
            itinerary      — the day-by-day plan text
            llm_calls      — total number of LLM invocations made
    """
    if not thread_id:
        thread_id = f"user_{uuid.uuid4().hex}"

    # config tells LangGraph which conversation thread to load/save state for
    config = {
        "configurable": {
            "thread_id": thread_id
        }
    }

    result = travel_graph.invoke(
        {
            "messages": [
                HumanMessage(content=user_input)
            ],
            "user_query": user_input,
            "flight_results": "",
            "hotel_results": "",
            "weather_results": "",
            "itinerary": "",
            "llm_calls": 0
        },
        config=config
    )

    # The last message in the list is always the final_agent's formatted response
    final_answer = result["messages"][-1].content

    return {
        "thread_id": thread_id,
        "answer": final_answer,
        "flight_results": result.get("flight_results", ""),
        "weather_results": result.get("weather_results", ""),
        "hotel_results": result.get("hotel_results", ""),
        "itinerary": result.get("itinerary", ""),
        "llm_calls": result.get("llm_calls", 0),
    }
