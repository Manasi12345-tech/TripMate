"""
TripMate Backend — LangGraph Multi-Agent Travel Planner
=======================================================

HOW THIS FILE FITS INTO THE PROJECT
------------------------------------
This is the core AI engine of TripMate. It wires together four specialized
AI agents into a sequential pipeline using LangGraph. The frontend (app.py)
calls run_travel_agent() and gets back a fully formatted travel plan.

HIGH-LEVEL FLOW
---------------
User Query
   │
   ▼
flight_agent  →  Searches for real flights using the Amadeus API
   │
   ▼
hotel_agent   →  Searches for hotels using Tavily web search
   │
   ▼
itinerary_agent  →  Asks the LLM to combine flights + hotels into a day-by-day plan
   │
   ▼
final_agent   →  Asks the LLM to format everything into a clean, user-facing response
   │
   ▼
Formatted travel plan returned to the caller

KEY CONCEPTS FOR BEGINNERS
---------------------------
1. LangGraph — a framework for building AI pipelines as a graph of nodes (agents)
   and edges (connections between them). Think of it like a flowchart where each
   box is an AI agent.

2. TravelState — a shared dictionary that every agent can read from and write to.
   It travels through the entire graph, accumulating results at each step.

3. Checkpointer — saves the state to PostgreSQL after every step. This means
   conversations persist across server restarts and multiple users are isolated
   by their thread_id.

4. thread_id — a unique ID per conversation. LangGraph uses it to load the right
   conversation history from Postgres on each new message.
"""

