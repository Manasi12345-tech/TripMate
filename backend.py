def get_database_url():
    """
    Reads the DATABASE_URL from the .env file and ensures SSL is enabled.
    Render PostgreSQL requires sslmode=require for external connections.
    """
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise ValueError(
            "DATABASE_URL is missing. Please add your Render PostgreSQL External Database URL to .env"
        )

    # Append sslmode=require if not already present
    if "sslmode=" not in database_url:
        separator = "&" if "?" in database_url else "?"
        database_url = f"{database_url}{separator}sslmode=require"

    return database_url


GROQ_API_KEY = os.getenv("GROQ_API_KEY")
if not GROQ_API_KEY:
    raise ValueError("GROQ_API_KEY is missing. Please add it to your .env file.")

# =========================
# LLM
# =========================
# ChatGroq gives us access to large language models hosted on Groq's fast
# inference platform. This LLM instance is shared by itinerary_agent and
# final_agent — the two agents that need natural language generation.

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    api_key=GROQ_API_KEY
)

# =========================
# State
# =========================
# TravelState is the shared "notebook" that all four agents pass around.
# Each agent reads what it needs and writes its results back.
#
# Field breakdown:
#   messages       — full conversation history; new messages are APPENDED
#                    (not replaced) thanks to the Annotated[..., operator.add] reducer
#   user_query     — the raw text the user typed (e.g. "Trip to Paris for 5 days")
#   flight_results — raw flight data from the Amadeus API (set by flight_agent)
#   hotel_results  — web search results for hotels (set by hotel_agent)
#   itinerary      — day-by-day plan generated by the LLM (set by itinerary_agent)
#   llm_calls      — running counter of how many LLM calls were made this run

class TravelState(TypedDict):
    messages: Annotated[list[AnyMessage], operator.add]
    user_query: str
    flight_results: str
    hotel_results: str
    itinerary: str
    llm_calls: int
    weather_results: str

